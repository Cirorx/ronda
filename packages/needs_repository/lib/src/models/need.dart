/// One thing that makes taking part hard for a member ("lo que te complica
/// ir").
///
/// The value names are the stored contract: renaming one drops it from every
/// phone that saved it.
enum Need {
  /// "Caminar mucho": far seats are out.
  walkALot,

  /// "Subir escaleras": seats with stairs are out.
  climbStairs,

  /// "Volver de noche": seats that end after dark are out.
  returnAfterDark,

  /// "No tengo auto": seats that need a car are out.
  noCar,
}
