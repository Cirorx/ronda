/// {@template app_radius}
/// Corner radii from the component sheet.
///
/// Buttons and cards use [lg]. Only the theme and the components read these.
/// {@endtemplate}
abstract final class AppRadius {
  /// 8: a segment inside a segmented control.
  static const double sm = 8;

  /// 10: a cell in the slot grid.
  static const double md = 10;

  /// 12: buttons, cards, banners.
  static const double lg = 12;

  /// 16: the top of a bottom sheet.
  static const double xl = 16;

  /// 22: pill chips.
  static const double pill = 22;
}
