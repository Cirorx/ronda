// Writes web/firebase-messaging-sw.js, the service worker FCM needs on web,
// from the web config in a generated options file:
//
//   dart run tool/firebase_messaging_sw.dart [lib/firebase_options_<flavor>.dart]
//
// The worker can't import Dart, so it carries the web config inline. That
// config comes from `flutterfire configure`, which stays out of git, so the
// worker is git-ignored too and generated after each configure
// (docs/STACK.md § Native and project checklist). Both flavors share one web
// app, so the development options are the default. Run it from the repo root.
import 'dart:io';

/// The Firebase JS SDK the worker loads: the compat scripts, at the version
/// the FCM web plugin needs (docs/STACK.md, gotcha 5).
const firebaseJsVersion = '13.1.0';

/// The options file read when none is given.
const defaultOptionsFile = 'lib/firebase_options_development.dart';

/// Where the worker is written; `flutter build web` copies it next to the app.
const workerFile = 'web/firebase-messaging-sw.js';

/// The `FirebaseOptions` fields the web SDK reads, in the order written.
const fields = [
  'apiKey',
  'authDomain',
  'projectId',
  'storageBucket',
  'messagingSenderId',
  'appId',
  'measurementId',
];

void main(List<String> args) {
  final optionsFile = args.isEmpty ? defaultOptionsFile : args.first;
  final source = File(optionsFile);
  if (!source.existsSync()) {
    stderr.writeln(
      '$optionsFile is missing: run `flutterfire configure` first '
      '(docs/STACK.md).',
    );
    exit(1);
  }
  final config = webConfig(source.readAsStringSync());
  if (config == null) {
    stderr.writeln('No `web` FirebaseOptions with an apiKey in $optionsFile.');
    exit(1);
  }
  File(workerFile).writeAsStringSync(worker(config));
  stdout.writeln('Wrote $workerFile from $optionsFile.');
}

/// The fields of the `static const FirebaseOptions web` block in [source], or
/// `null` when there is no such block or it has no apiKey.
Map<String, String>? webConfig(String source) {
  final block = RegExp(
    r'FirebaseOptions\s+web\s*=\s*FirebaseOptions\(([^)]*)\)',
  ).firstMatch(source);
  if (block == null) return null;
  final config = {
    for (final match in RegExp(
      r"(\w+):\s*'([^']*)'",
    ).allMatches(block.group(1)!))
      if (fields.contains(match.group(1))) match.group(1)!: match.group(2)!,
  };
  return config.containsKey('apiKey') ? config : null;
}

/// The worker's source for [config].
String worker(Map<String, String> config) {
  final lines = [
    for (final field in fields)
      if (config[field] case final value?) "  $field: '$value',",
  ];
  return '''
// Generated by tool/firebase_messaging_sw.dart from the flutterfire options;
// git-ignored, like them. Regenerate instead of editing it.
//
// FCM's service worker on web: it receives pushes while no Ronda tab is in
// front. A push with a notification block is shown by the SDK itself, which
// is the payload web gets (docs/STACK.md § Push).
importScripts('https://www.gstatic.com/firebasejs/$firebaseJsVersion/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/$firebaseJsVersion/firebase-messaging-compat.js');

firebase.initializeApp({
${lines.join('\n')}
});

firebase.messaging();
''';
}
